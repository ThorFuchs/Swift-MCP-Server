private enum RetirementProbeError: Error, Equatable { case stopped, readiness }
private final class RetirementSignal: Sendable {
    private let pair = AsyncStream<Void>.makeStream(bufferingPolicy: .bufferingNewest(1))
    func send() { pair.continuation.yield(()); pair.continuation.finish() }
    func wait() async throws {
        try await withThrowingTaskGroup(of: Void.self) { group in
            group.addTask {
                var iterator = self.pair.stream.makeAsyncIterator()
                guard await iterator.next() != nil else { throw RetirementProbeError.readiness }
            }
            group.addTask {
                try await Task.sleep(for: .seconds(10))
                throw RetirementProbeError.readiness
            }
            defer { group.cancelAll() }
            _ = try await group.next()
        }
    }
}

private final class RetirementLog: Sendable {
    private let lines = Mutex<[String]>([])
    private let ready = Mutex(RetirementSignal())
    func prepare() -> RetirementSignal {
        let signal = RetirementSignal()
        ready.withLock { $0 = signal }
        return signal
    }
    func append(_ line: String) {
        lines.withLock { $0.append(line) }
        print("A22B3B_PEER \(line)")
        if line == "READY" {
            let signal = ready.withLock { $0 }
            signal.send()
        }
    }
    var snapshot: [String] { lines.withLock { $0 } }
}

// All inputs are generated by the test helper below, with numeric IDs and
// ASCII string or integer tokens. Log method/ID, not large token payloads.
// Every accidentally admitted refusal probe receives a finite response.
private let retirementPeer = #"""
    printf '%s\n' READY >&2
    while IFS= read -r line; do
        case "$line" in
            *'"method":"notifications/cancelled"'*)
                id=${line#*'"requestId":'}; id=${id%%\}*}
                printf 'RX:cancel:%s\n' "$id" >&2
                continue ;;
        esac
        id=${line#*'"id":'}; id=${id%%,*}
        method=${line#*'"method":"'}; method=${method%%\"*}
        token=${line#*'"progressToken":'}; token=${token%%\}*}
        printf 'RX:%s:%s\n' "$method" "$id" >&2
        case "$method" in
            probe/retire)
                printf '{"jsonrpc":"2.0","method":"notifications/progress","params":{"progressToken":%s,"progress":1}}\n' "$token" ;;
            probe/active)
                printf '{"jsonrpc":"2.0","method":"notifications/progress","params":{"progressToken":%s,"progress":1}}\n' "$token"
                printf '{"jsonrpc":"2.0","id":%s,"result":{}}\n' "$id" ;;
            probe/barrier)
                printf '%s\n' '{"jsonrpc":"2.0","id":71,"result":{}}'
                printf '%s\n' '{"jsonrpc":"2.0","method":"notifications/progress","params":{"progressToken":"shared","progress":99}}'
                printf '%s\n' TX:late-id-and-token >&2
                printf '{"jsonrpc":"2.0","method":"notifications/progress","params":{"progressToken":%s,"progress":1}}\n' "$token"
                printf '{"jsonrpc":"2.0","id":%s,"result":{}}\n' "$id" ;;
            probe/complete|probe/refused)
                printf '{"jsonrpc":"2.0","id":%s,"result":{}}\n' "$id" ;;
            probe/mismatch)
                printf '%s\n' '{"jsonrpc":"2.0","id":71,"result":{}}' ;;
            probe/error)
                printf '{"jsonrpc":"2.0","id":%s,"error":{"code":-32603,"message":"probe"}}\n' "$id" ;;
            probe/malformed)
                printf '{"jsonrpc":"2.0","id":%s}\n' "$id" ;;
            probe/malformed-error)
                printf '{"jsonrpc":"2.0","id":%s,"error":{"code":0.5}}\n' "$id" ;;
            probe/dual)
                printf '{"jsonrpc":"2.0","id":%s,"result":{},"error":{"code":-32603,"message":"probe"}}\n' "$id" ;;
            subscriptions/listen)
                printf '{"jsonrpc":"2.0","id":%s,"result":{"resultType":"complete","_meta":{"io.modelcontextprotocol/subscriptionId":999}}}\n' "$id" ;;
            *) exit 41 ;;
        esac
    done
    printf '%s\n' CLEAN >&2
    exit 0
    """#

private func retirementRequest(_ method: String, id: Int, token: String? = nil, wireID: Int? = nil) -> OutgoingRequest {
    let params = token.map { #","params":{"_meta":{"progressToken":\#($0)}}"# } ?? ""
    return .init(id: .integer(JSONNumber(integer: id)), method: method, name: nil,
        body: Data(#"{"jsonrpc":"2.0","id":\#(wireID ?? id),"method":"\#(method)"\#(params)}"#.utf8))
}
private func retirementObject(_ bytes: Data) throws -> JSONObject {
    try #require(try WireCodec.parse(Array(bytes), limits: .balanced).result.objectValue)
}
private func retirementTransport(_ log: RetirementLog) -> StdioClientTransport {
    StdioClientTransport(configuration: .init(executable: .path("/bin/sh"),
        arguments: ["-c", retirementPeer], maximumPendingRequests: 2,
        maximumMessageBytes: 131072, standardError: { log.append($0) }))
}
private func retirementRun(_ transport: StdioClientTransport, log: RetirementLog,
    _ body: @Sendable (StdioClientTransport) async throws -> Void) async throws {
    let ready = log.prepare()
    try await withThrowingTaskGroup(of: Void.self) { group in
        group.addTask { try await transport.run() }
        do { try await ready.wait(); try await body(transport) }
        catch { transport.shutdown(); group.cancelAll(); throw error }
        transport.shutdown()
        try await group.waitForAll()
    }
    #expect(log.snapshot.last == "CLEAN")
}
private func abandon(_ transport: StdioClientTransport, id: Int, token: String) async throws {
    await #expect(throws: RetirementProbeError.stopped) {
        try await transport.exchange(retirementRequest("probe/retire", id: id, token: token)) { bytes in
            let object = try retirementObject(bytes)
            #expect(object["method"]?.stringValue == "notifications/progress")
            let expected = try WireCodec.parse(Array(token.utf8), limits: .balanced).result
            #expect(object["params"]?.objectValue?["progressToken"] == expected)
            throw RetirementProbeError.stopped
        }
    }
}
private func refuse(_ transport: StdioClientTransport, id: Int, token: String? = nil) async throws {
    await #expect(throws: StdioClientTransportError.busy) {
        try await transport.exchange(retirementRequest("probe/refused", id: id, token: token)) { _ in
            Issue.record("refused identity reached receiver")
        }
    }
}
private func complete(_ transport: StdioClientTransport, id: Int, token: String? = nil) async throws {
    try await transport.exchange(retirementRequest("probe/complete", id: id, token: token)) { bytes in
        let object = try retirementObject(bytes)
        #expect(object["id"] == .number(JSONNumber(integer: id)))
        #expect(object["result"]?.objectValue != nil)
    }
}

// Cancellation receipt IDs are JSON numbers, not decimal-format strings.
// Preserve the raw peer log; compare only these IDs by mathematical value.
private enum RetirementWireReceipt: Equatable {
    case cancellation(JSONNumber)
    case verbatim(String)
}

private func retirementWireReceipts(_ lines: [String]) throws -> [RetirementWireReceipt] {
    try lines.map { line in
        let prefix = "RX:cancel:"
        guard line.hasPrefix(prefix) else { return .verbatim(line) }
        let number = try JSONNumber(parsing: String(line.dropFirst(prefix.count)))
        guard number.isInteger else { throw WireFailure.invalidRequest }
        return .cancellation(number)
    }
}

@Suite(.serialized, .timeLimit(.minutes(1))) struct StdioRetirementCases {
    @Test func unansweredIDAndTokenStayReservedAfterLateFrames() async throws {
        let log = RetirementLog(), trace = Mutex<[String]>([])
        let transport = retirementTransport(log)
        try await retirementRun(transport, log: log) { transport in
            try await abandon(transport, id: 71, token: #""shared""#)
            try await refuse(transport, id: 71)
            try await refuse(transport, id: 72, token: #""shared""#)
            try await transport.exchange(retirementRequest("probe/barrier", id: 73, token: #""fresh""#)) { bytes in
                let object = try retirementObject(bytes)
                if object["method"] != nil {
                    let token = try #require(object["params"]?.objectValue?["progressToken"]?.stringValue)
                    trace.withLock { $0.append(token) }
                } else {
                    #expect(object["id"] == .number(JSONNumber(integer: 73)))
                    trace.withLock { $0.append("terminal") }
                }
            }
            try await refuse(transport, id: 71)
            try await refuse(transport, id: 72, token: #""shared""#)
            try await complete(transport, id: 74)
        }
        #expect(trace.withLock { $0 } == ["fresh", "terminal"])
        #expect(log.snapshot == ["READY", "RX:probe/retire:71", "RX:cancel:71",
            "RX:probe/barrier:73", "TX:late-id-and-token", "RX:probe/complete:74", "CLEAN"])
        print("A22B3B_LATE trace=\(trace.withLock { $0 })")
    }

    @Test func countBudgetIncludesActiveReservationsAndResetsOnRestart() async throws {
        let log = RetirementLog(), transport = retirementTransport(log)
        try await retirementRun(transport, log: log) { transport in
            for id in 1...127 { try await abandon(transport, id: id, token: String(id)) }
            // 254 retained keys + the two active keys exhaust the 256-key budget.
            try await transport.exchange(retirementRequest("probe/active", id: 128, token: "128")) { bytes in
                let object = try retirementObject(bytes)
                if object["method"] != nil {
                    try await refuse(transport, id: 1000)
                } else { #expect(object["id"] == .number(JSONNumber(integer: 128))) }
            }
            // The completed route released two reservations; they can be
            // acquired once more, then remain retained after local failure.
            try await abandon(transport, id: 128, token: "128")
            try await refuse(transport, id: 1001)
            try await refuse(transport, id: 1)
            try await refuse(transport, id: 1002, token: "1")
        }
        let expected = ["READY"] + (1...127).flatMap { ["RX:probe/retire:\($0)", "RX:cancel:\($0)"] }
            + ["RX:probe/active:128", "RX:probe/retire:128", "RX:cancel:128", "CLEAN"]
        let firstRun = try retirementWireReceipts(log.snapshot)
        let expectedFirstRun = try retirementWireReceipts(expected)
        #expect(firstRun == expectedFirstRun)
        try await retirementRun(transport, log: log) { transport in
            try await complete(transport, id: 1, token: "1")
        }
        let bothRuns = try retirementWireReceipts(log.snapshot)
        let expectedBothRuns = try retirementWireReceipts(expected + ["READY", "RX:probe/complete:1", "CLEAN"])
        #expect(bothRuns == expectedBothRuns)
        print("A22B3B_COUNT retired=256 restart=true")
    }

    @Test func byteBudgetRefusesLargeKeysBeforeWireWithCountHeadroom() async throws {
        let log = RetirementLog(), transport = retirementTransport(log)
        // Distinct 65,536 UTF-8 byte tokens. Three fit; four cannot fit
        // the 256 KiB charged-key budget including per-identity overhead.
        let tokens = (1...4).map { #""\#($0)\#(String(repeating: "x", count: 65535))""# }
        try await retirementRun(transport, log: log) { transport in
            for i in 0..<3 { try await abandon(transport, id: i + 1, token: tokens[i]) }
            try await refuse(transport, id: 4, token: tokens[3])
            try await complete(transport, id: 4, token: "4")
            try await refuse(transport, id: 5, token: tokens[0])
        }
        #expect(log.snapshot == ["READY", "RX:probe/retire:1", "RX:cancel:1",
            "RX:probe/retire:2", "RX:cancel:2", "RX:probe/retire:3", "RX:cancel:3",
            "RX:probe/complete:4", "CLEAN"])
        print("A22B3B_BYTES large=3 refused=1 small-recovery=true")
    }

    @Test func terminalResultAndErrorReleaseBothNamespaces() async throws {
        let log = RetirementLog(), transport = retirementTransport(log)
        try await retirementRun(transport, log: log) { transport in
            try await complete(transport, id: 71, token: "71")
            await #expect(throws: RetirementProbeError.stopped) {
                try await transport.exchange(retirementRequest("probe/error", id: 71, token: "71")) { bytes in
                    let object = try retirementObject(bytes)
                    #expect(object["error"]?.objectValue?["code"] == .number(JSONNumber(integer: -32603)))
                    throw RetirementProbeError.stopped
                }
            }
            try await complete(transport, id: 71, token: "71")
            // Request IDs and progress tokens have different namespaces.
            try await abandon(transport, id: 72, token: "73")
            try await complete(transport, id: 73, token: "72")
        }
        #expect(log.snapshot == ["READY", "RX:probe/complete:71", "RX:probe/error:71",
            "RX:probe/complete:71", "RX:probe/retire:72", "RX:cancel:72", "RX:probe/complete:73", "CLEAN"])
        print("A22B3B_TERMINAL result-and-error-reuse=true namespaces=true")
    }

    @Test func malformedTerminalCandidatesDoNotAuthorizeReuse() async throws {
        let log = RetirementLog(), transport = retirementTransport(log)
        let methods = ["probe/malformed", "probe/malformed-error", "probe/dual", "subscriptions/listen"]
        try await retirementRun(transport, log: log) { transport in
            for (index, method) in methods.enumerated() {
                let id = 71 + index
                try await transport.exchange(retirementRequest(method, id: id, token: String(id))) { bytes in
                    let object = try retirementObject(bytes)
                    #expect(object["id"] == .number(JSONNumber(integer: id)))
                    // Raw transport still delivers the candidate for client validation.
                }
                try await refuse(transport, id: id)
                try await refuse(transport, id: 100 + index, token: String(id))
            }
            try await complete(transport, id: 80)
        }
        let expected = ["READY"] + methods.enumerated().map { "RX:\($0.element):\(71 + $0.offset)" }
            + ["RX:probe/complete:80", "CLEAN"]
        #expect(log.snapshot == expected)
        print("A22B3B_MALFORMED retained=4 recovery=true")
    }

    @Test func mismatchedOutgoingIdentityNeverAcquiresReservationOrWire() async throws {
        let log = RetirementLog(), transport = retirementTransport(log)
        try await retirementRun(transport, log: log) { transport in
            // Both possible IDs must remain available after local refusal.
            await #expect(throws: WireFailure.invalidRequest) {
                try await transport.exchange(retirementRequest("probe/mismatch", id: 71, token: "71", wireID: 72)) { _ in
                    Issue.record("mismatched outgoing request reached receiver")
                }
            }
            try await complete(transport, id: 71, token: "71")
            try await complete(transport, id: 72, token: "71")
        }
        #expect(log.snapshot == ["READY", "RX:probe/complete:71", "RX:probe/complete:72", "CLEAN"])
        print("A22B3B_OUTGOING mismatch-refused=true recovery=true")
    }
}
